bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case KC_LLOCK:
            if (record->event.pressed) {
                layer_lock_invert(get_highest_layer(layer_state));
            }
            return false;

        default:
            return true;
    }
}

// Tell keymap.c that this variable exists in keychron_rgb.c
extern os_indicator_config_t os_ind_cfg;

bool rgb_matrix_indicators_user(void) {
    uint8_t layer = get_highest_layer(layer_state);

    if (layer >= 1 && layer <= 12) {
        // Grab the specific color used for Caps/Num Lock
        RGB color = hsv_to_rgb(os_ind_cfg.hsv);
        
        // Light up the corresponding number key / layer indicator key
        rgb_matrix_set_color(layer, color.r, color.g, color.b);
    }
	
    return true;
}